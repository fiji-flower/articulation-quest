const SOUND_DIGRAPHS=["tch","dge","sh","ch","th","ng","ph","wh","qu","ck","gh","kn","wr","zh","dh"];
const DIGRAPH_ORDER=[...SOUND_DIGRAPHS].sort((a,b)=>b.length-a.length);

function targetUnits(target){
 const units=new Set();
 String(target||"").replace(/\band\b/gi,",").split(/[,\/&+\u2013\u2014]/).forEach(raw=>{
  const t=raw.trim().toLowerCase().replace(/[.()]/g,"");
  if(!t)return;
  const soft=t.match(/^soft\s+([a-z])$/);
  if(soft){units.add("soft-"+soft[1]);return}
  if(/^[a-z]$/.test(t)||SOUND_DIGRAPHS.includes(t))units.add(t);
 });
 return units;
}

function highlight(s,target){
 const units=targetUnits(target), text=String(s);
 if(!units.size)return escapeHTML(text);
 const lower=text.toLowerCase();
 const digraphs=[...units].filter(u=>u.length>1&&!u.startsWith("soft-")).sort((a,b)=>b.length-a.length);
 const softUnits=[...units].filter(u=>u.startsWith("soft-")).map(u=>u.slice(5));
 const wrap=str=>`<span class="target">${escapeHTML(str)}</span>`;
 let out="",i=0;
 while(i<text.length){
  const unit=digraphs.find(u=>lower.startsWith(u,i));
  if(unit){out+=wrap(text.substr(i,unit.length));i+=unit.length;continue}
  if(softUnits.includes(lower[i])&&/[eiy]/.test(lower[i+1]||"")){out+=wrap(text[i]);i++;continue}
  const digraph=DIGRAPH_ORDER.find(d=>lower.startsWith(d,i));
  if(digraph){out+=escapeHTML(text.substr(i,digraph.length));i+=digraph.length;continue}
  if(units.has(lower[i])){out+=wrap(text[i]);i++;continue}
  out+=escapeHTML(text[i]);i++;
 }
 return out;
}
function escapeHTML(s){return String(s).replace(/[&<>"']/g,m=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#039;"}[m]))}

